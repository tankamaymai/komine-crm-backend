-- 埋葬者に「最終納骨者」フラグを追加する（会議議事録 2026-07-21 §1）。
--
-- 業務要望: 最後の納骨者を登録した時点から合祀までの所定年数のカウントダウンを開始したい。
-- 契約人数と実際の納骨人数が一致しないケース（4人契約だが3人で終了）があるため、
-- 埋葬上限人数の到達では最終納骨を判定できず、運用側の明示指定が必要になる。
--
-- 既存行は false（＝最終納骨者未確定）で開始する。この状態では合祀予定日は
-- 従来どおり契約日起点で算出されるため、移行時点の請求スケジュールは変化しない。
ALTER TABLE "buried_persons"
  ADD COLUMN "is_final_burial" BOOLEAN NOT NULL DEFAULT false;

-- 合祀予定日を業務が手動指定したかを記録する。
--
-- 最終納骨者の埋葬日を起点に合祀予定日を自動再計算するようになると、
-- PUT /collective-burials/:id で手動指定された予定日（例外運用: 決まった年数より
-- 短くする等。業務確認 2026-06-07 Q17）を上書きしてしまう。自動値と手動値を
-- 区別する情報が無いため、明示フラグで保護する。
--
-- 既存行は false（自動再計算の対象）で開始する。移行時点では最終納骨者が
-- 全件未確定のため起点は契約日のままで、請求スケジュールは変化しない。
ALTER TABLE "collective_burials"
  ADD COLUMN "billing_scheduled_date_manual" BOOLEAN NOT NULL DEFAULT false;
